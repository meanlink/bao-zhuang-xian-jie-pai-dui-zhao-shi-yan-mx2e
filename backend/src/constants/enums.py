from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
    cancelled = 'cancelled'
class JobEventName(str, Enum):
    queued = 'queued'
    claimed = 'claimed'
    lost = 'lost'
    reclaimed = 'reclaimed'
    completed = 'completed'
    failed = 'failed'
    cancelled = 'cancelled'
